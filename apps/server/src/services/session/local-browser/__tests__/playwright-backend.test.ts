import { describe, expect, it, beforeEach, vi } from 'vitest';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { PassThrough } from 'node:stream';
import { chromium, type BrowserContext } from 'playwright-core';
import { lexWithoutComments } from '../../../../../../../scripts/lib/code-only.mjs';
const mocks = vi.hoisted(() => ({
  chromePath: vi.fn((): string | undefined => undefined),
  access: vi.fn(),
  mkdir: vi.fn(async () => undefined),
  readFile: vi.fn(async () => '{}'),
  writeFile: vi.fn(async () => undefined),
  rm: vi.fn(async () => undefined),
  stdout: undefined as PassThrough | undefined,
  failure: undefined as undefined | { code?: string; stderr?: string },
  execFile: vi.fn((...args: unknown[]) => {
    const done = args.at(-1) as (error: unknown, stdout?: string, stderr?: string) => void;
    done(mocks.failure, '', '');
    return { stdout: mocks.stdout };
  }),
}));
vi.mock('../connection/chrome-installation.js', () => ({ installedChromePath: mocks.chromePath }));
vi.mock('node:fs/promises', () => ({
  access: mocks.access,
  mkdir: mocks.mkdir,
  readFile: mocks.readFile,
  writeFile: mocks.writeFile,
  rm: mocks.rm,
}));
vi.mock('node:child_process', () => {
  // Match Node's custom promisify contract: its promise retains the observable child.
  const execFile = Object.assign(mocks.execFile, {
    [Symbol.for('nodejs.util.promisify.custom')]: (...args: unknown[]) => {
      let child: ReturnType<typeof mocks.execFile> | undefined;
      const result = new Promise((resolve, reject) => {
        child = mocks.execFile(...args, (error: unknown, stdout: string, stderr: string) => {
          if (error) reject(error);
          else resolve({ stdout, stderr });
        });
      });
      return Object.assign(result, { child });
    },
  });
  return { execFile };
});
/** A window whose theme data reports this frame colour. */
function themedContext(frame = '#b6520b'): BrowserContext {
  return {
    newPage: vi.fn(async () => ({
      goto: vi.fn(async () => null),
      evaluate: vi.fn(async () => `--color-frame-active:${frame}ff;`),
      close: vi.fn(async () => undefined),
    })),
    close: vi.fn(async (): Promise<void> => undefined),
  } as unknown as BrowserContext;
}
import {
  acquireLocalChromium,
  LOCAL_MANAGED_CHROMIUM_VERSION,
  productionBackend,
} from '../playwright-backend.js';

beforeEach(() => {
  mocks.execFile.mockClear();
  mocks.writeFile.mockClear();
  mocks.chromePath.mockReturnValue(undefined);
  mocks.stdout = new PassThrough();
  mocks.access.mockRejectedValue(Object.assign(new Error('Missing browser'), { code: 'ENOENT' }));
  mocks.failure = undefined;
});
describe('pinned managed browser preparation', () => {
  it('uses installed Chrome without downloading Chromium or requiring a theme extension', async () => {
    mocks.chromePath.mockReturnValue('/installed/chrome');
    const context = themedContext();
    const launch = vi.spyOn(chromium, 'launchPersistentContext').mockResolvedValue(context);
    try {
      await productionBackend.launch('test-only-storage');
      expect(launch.mock.calls[0]![1]).toMatchObject({ channel: 'chrome' });
      expect(mocks.execFile).not.toHaveBeenCalled();
      expect(context.newPage).not.toHaveBeenCalled();
    } finally {
      launch.mockRestore();
    }
  });
  it('writes the installed Chrome orange, agent name and avatar before launch with extensions disabled', async () => {
    mocks.chromePath.mockReturnValue('/installed/chrome');
    const launch = vi
      .spyOn(chromium, 'launchPersistentContext')
      .mockImplementation(async (_folder, options) => {
        const writes = mocks.writeFile.mock.calls as unknown as [string, string][];
        const prefs = JSON.parse(
          writes.filter(([file]) => file.endsWith('Preferences')).at(-1)![1]
        );
        const localWrite = writes.find(([file]) => file.endsWith('Local State'));
        expect(localWrite).toBeDefined();
        const local = JSON.parse(localWrite![1]);
        expect(prefs).toMatchObject({
          autogenerated: { theme: { color: -4828661 } },
          extensions: { theme: { id: 'autogenerated_theme_id' } },
          profile: { name: 'Atlas · DorkOS', avatar_index: 8, using_gaia_avatar: false },
        });
        expect(local.profile.info_cache.Default).toMatchObject({
          name: 'Atlas · DorkOS',
          avatar_icon: 'chrome://theme/IDR_PROFILE_AVATAR_8',
        });
        expect(options?.ignoreDefaultArgs).not.toContain('--disable-extensions');
        expect(options?.args?.join(' ')).not.toMatch(/load-extension|disable-extensions-except/);
        return themedContext();
      });
    try {
      await productionBackend.launch('test-only-storage', undefined, undefined, 'Atlas');
    } finally {
      launch.mockRestore();
    }
  });
  it('reuses the installed executable without an installer process', async () => {
    mocks.access.mockResolvedValue(undefined);
    await acquireLocalChromium();
    expect(mocks.execFile).not.toHaveBeenCalled();
  });
  it('streams only genuine sanitized downloader progress and removes the listener', async () => {
    const report = vi.fn();
    mocks.execFile.mockImplementationOnce((...args: unknown[]) => {
      const done = args.at(-1) as (error: unknown, stdout?: string, stderr?: string) => void;
      queueMicrotask(() => {
        mocks.stdout!.write(
          'Downloading Chrome for Testing 157 from https://private/token\n|■■|  40% of 100 MiB\n'
        );
        done(undefined, '', '');
      });
      return { stdout: mocks.stdout };
    });
    await acquireLocalChromium(undefined, report);
    expect(report.mock.calls.map(([state]) => state)).toEqual([
      { stage: 'checking', component: null, percent: null },
      { stage: 'downloading', component: null, percent: null },
      { stage: 'downloading', component: 'chromium', percent: null },
      { stage: 'downloading', component: 'chromium', percent: 40 },
    ]);
    expect(mocks.stdout!.listenerCount('data')).toBe(0);
    expect(JSON.stringify(report.mock.calls)).not.toContain('private');
  });
  it('reports launching only after the installed executable is checked', async () => {
    mocks.access.mockResolvedValue(undefined);
    const report = vi.fn();
    const launch = vi.spyOn(chromium, 'launchPersistentContext').mockResolvedValue(themedContext());
    try {
      await productionBackend.launch('test-only-storage', undefined, report);
      expect(report.mock.calls.map(([state]) => state)).toEqual([
        { stage: 'checking', component: null, percent: null },
        { stage: 'launching', component: null, percent: null },
      ]);
      // Check against the real pinned package, not a second copy of our feature list.
      const require = createRequire(import.meta.url);
      const bundle = readFileSync(
        path.join(
          path.dirname(require.resolve('playwright-core/package.json')),
          'lib/coreBundle.js'
        ),
        'utf8'
      );
      const array = bundle.match(/disabledFeatures = (\[[\s\S]*?\])\.filter\(Boolean\);/)?.[1];
      expect(array).toBeDefined();
      const lexed = lexWithoutComments(array!, 'pinned-disabled-features.js');
      expect(lexed.parseErrors).toBe(0);
      const features = JSON.parse(lexed.code.replace(/,\s*\]/, ']'));
      const defaultFeatures = `--disable-features=${features.join(',')}`;
      expect(launch).toHaveBeenCalledExactlyOnceWith('test-only-storage', {
        timeout: 15_000,
        headless: false,
        viewport: null,
        chromiumSandbox: true,
        // Keep the pinned feature overrides and allow only the theme extension.
        args: [
          `${defaultFeatures},HttpsUpgrades,HttpsFirstBalancedModeAutoEnable`,
          `--disable-extensions-except=${path.join('.agent-window-theme')}`,
          `--load-extension=${path.join('.agent-window-theme')}`,
          '--window-name=An agent is using this window',
        ],
        ignoreDefaultArgs: ['--enable-automation', defaultFeatures, '--disable-extensions'],
      });
      expect(mocks.execFile).not.toHaveBeenCalled();
      // The agent's window shares the profile with the sign-in window: neither saves passwords.
      const [file, written] = (mocks.writeFile.mock.calls as unknown as [string, string][]).find(
        ([target]) => target.endsWith('Preferences')
      )!;
      expect(file).toMatch(/test-only-storage[\\/]Default[\\/]Preferences$/);
      expect(JSON.parse(written)).toMatchObject({
        credentials_enable_service: false,
        profile: { password_manager_enabled: false },
      });
      expect(mocks.writeFile.mock.invocationCallOrder.at(-1)).toBeLessThan(
        launch.mock.invocationCallOrder[0]!
      );
    } finally {
      launch.mockRestore();
    }
  });
  it('names the window after the chat’s agent (DOR-3111)', async () => {
    mocks.access.mockResolvedValue(undefined);
    const launch = vi.spyOn(chromium, 'launchPersistentContext').mockResolvedValue(themedContext());
    try {
      await productionBackend.launch('test-only-storage', undefined, undefined, 'Atlas');
      const [, options] = launch.mock.calls[0]!;
      expect(options?.args).toContain('--window-name=Atlas is using this window');
      expect(options?.args?.filter((arg) => arg.startsWith('--window-name='))).toHaveLength(1);
    } finally {
      launch.mockRestore();
    }
  });
  it('closes and refuses a window that didn’t come up orange', async () => {
    mocks.access.mockResolvedValue(undefined);
    const context = themedContext('#1f2020');
    const launch = vi.spyOn(chromium, 'launchPersistentContext').mockResolvedValue(context);
    try {
      await expect(productionBackend.launch('test-only-storage')).rejects.toMatchObject({
        code: 'window_unlabelled',
      });
      expect(context.close).toHaveBeenCalled();
    } finally {
      launch.mockRestore();
    }
  });
  it('returns a context that arrives after abort so the service can close its owned browser', async () => {
    mocks.access.mockResolvedValue(undefined);
    const controller = new AbortController();
    const context = themedContext();
    let finish!: (context: BrowserContext) => void;
    const launch = vi.spyOn(chromium, 'launchPersistentContext').mockImplementationOnce(
      () =>
        new Promise<BrowserContext>((resolve) => {
          finish = resolve;
        })
    );
    try {
      const opening = productionBackend.launch('test-only-storage', controller.signal);
      await vi.waitFor(() => expect(launch).toHaveBeenCalledOnce());
      controller.abort();
      finish(context);
      expect(await opening).toBe(context);
      expect(context.close).not.toHaveBeenCalled();
    } finally {
      launch.mockRestore();
    }
  });
  it('runs only the installed package installer with a bounded acquisition', async () => {
    await acquireLocalChromium();
    const [binary, args, options] = mocks.execFile.mock.calls[0];
    expect(binary).toBe(process.execPath);
    expect(args).toEqual([
      expect.stringMatching(/playwright-core[/\\]cli\.js$/),
      'install',
      'chromium',
    ]);
    expect(options).toMatchObject({ timeout: 180_000, env: { ELECTRON_RUN_AS_NODE: '1' } });
  });
  it.each([
    [{ code: 'ENOSPC' }, 'browser_storage', 'Free some space'],
    [{ stderr: 'EACCES confidential/path' }, 'browser_storage', 'Check folder permissions'],
    [{ stderr: 'proxy refused confidential/token' }, 'browser_download', 'Check your connection'],
  ])(
    'returns plain recovery guidance without exposing installer details',
    async (failure, code, guidance) => {
      mocks.failure = failure;
      await expect(acquireLocalChromium()).rejects.toMatchObject({
        code,
        message: expect.stringContaining(guidance),
      });
      try {
        await acquireLocalChromium();
      } catch (error) {
        expect((error as Error).message).not.toContain('confidential');
      }
    }
  );
  it('cancels an in-flight installer through its abort signal', async () => {
    const controller = new AbortController();
    const report = vi.fn();
    mocks.execFile.mockImplementationOnce((...args: unknown[]) => {
      const options = args[2] as { signal: AbortSignal };
      const done = args.at(-1) as (error: unknown) => void;
      options.signal.addEventListener(
        'abort',
        () => {
          mocks.stdout!.write(
            'Downloading Chromium from https://private/token\n|■■|  80% of 100 MiB\n'
          );
          done({ code: 'ABORT_ERR' });
        },
        { once: true }
      );
      return { stdout: mocks.stdout };
    });
    const preparing = acquireLocalChromium(controller.signal, report);
    const refused = expect(preparing).rejects.toMatchObject({ code: 'cancelled' });
    await vi.waitFor(() => expect(mocks.execFile).toHaveBeenCalledOnce());
    controller.abort();
    await refused;
    expect(report.mock.calls.map(([state]) => state)).toEqual([
      { stage: 'checking', component: null, percent: null },
      { stage: 'downloading', component: null, percent: null },
    ]);
    expect(mocks.stdout!.listenerCount('data')).toBe(0);
  });
  it('reports the browser revision actually paired with its packaged library', () => {
    const require = createRequire(import.meta.url);
    const { browsers } = require(
      path.join(path.dirname(require.resolve('playwright-core/package.json')), 'browsers.json')
    );
    expect(
      browsers.find((browser: { name: string }) => browser.name === 'chromium').browserVersion
    ).toBe(LOCAL_MANAGED_CHROMIUM_VERSION);
  });
});

/** Built-in Chrome profile labels. No extension, page script or browser flag. */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { AGENT_FRAME_RGB } from './theme.js';

// Chromium ThemeService's built-in theme id and signed SkColor (opaque ARGB).
// https://chromium.googlesource.com/chromium/src/+/main/chrome/browser/themes/theme_service.cc
export const AGENT_CHROME_COLOR =
  0xff000000 | (AGENT_FRAME_RGB[0] << 16) | (AGENT_FRAME_RGB[1] << 8) | AGENT_FRAME_RGB[2];
// Chromium’s built-in secret-agent avatar, distinct from its generic person icon.
export const AGENT_CHROME_AVATAR = 8;
const AUTO_THEME = 'autogenerated_theme_id';
const SUFFIX = ' · DorkOS';
type Prefs = Record<string, unknown>;
const section = (value: unknown): Prefs =>
  value && typeof value === 'object' && !Array.isArray(value) ? (value as Prefs) : {};
async function readPrefs(file: string): Promise<Prefs> {
  try {
    return section(JSON.parse(await readFile(file, 'utf8')));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return {};
    throw error;
  }
}
async function writePrefs(file: string, prefs: Prefs): Promise<void> {
  await mkdir(path.dirname(file), { recursive: true, mode: 0o700 });
  await writeFile(file, JSON.stringify(prefs), { mode: 0o600 });
}

/** Before launching installed Chrome on DorkOS's own profile, label its native frame and avatar. */
export async function writeAgentChromeProfile(
  folder: string,
  agentName?: string | null
): Promise<void> {
  const file = path.join(folder, 'Default', 'Preferences');
  const prefs = await readPrefs(file);
  const name = `${agentName?.trim() || 'Agent'}${SUFFIX}`;
  const extensions = section(prefs.extensions);
  prefs.extensions = { ...extensions, theme: { id: AUTO_THEME } };
  prefs.autogenerated = { ...section(prefs.autogenerated), theme: { color: AGENT_CHROME_COLOR } };
  prefs.profile = {
    ...section(prefs.profile),
    name,
    avatar_index: AGENT_CHROME_AVATAR,
    using_default_name: false,
    using_default_avatar: false,
    using_gaia_avatar: false,
  };
  await writePrefs(file, prefs);
  await writeLocalLabel(folder, name, AGENT_CHROME_AVATAR);
}

/** A plain handoff must not keep the agent's orange or its name. Other profiles stay untouched. */
export async function clearAgentChromeProfile(folder: string): Promise<void> {
  const file = path.join(folder, 'Default', 'Preferences');
  const prefs = await readPrefs(file);
  const profile = section(prefs.profile);
  if (typeof profile.name !== 'string' || !profile.name.endsWith(SUFFIX)) return;
  const extensions = section(prefs.extensions);
  const generated = section(prefs.autogenerated);
  if (
    section(extensions.theme).id === AUTO_THEME &&
    section(generated.theme).color === AGENT_CHROME_COLOR
  ) {
    delete extensions.theme;
    delete generated.theme;
  }
  prefs.profile = { ...profile, name: `You${SUFFIX}`, avatar_index: 0 };
  await writePrefs(file, prefs);
  await writeLocalLabel(folder, `You${SUFFIX}`, 0);
}

async function writeLocalLabel(folder: string, name: string, avatar: number): Promise<void> {
  const file = path.join(folder, 'Local State');
  const local = await readPrefs(file);
  const profile = section(local.profile);
  const cache = section(profile.info_cache);
  local.profile = {
    ...profile,
    info_cache: {
      ...cache,
      Default: {
        ...section(cache.Default),
        name,
        avatar_icon: `chrome://theme/IDR_PROFILE_AVATAR_${avatar}`,
        is_using_default_name: false,
        is_using_default_avatar: false,
        use_gaia_picture: false,
      },
    },
  };
  await writePrefs(file, local);
}

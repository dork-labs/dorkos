/**
 * Whether two handles look alike: the Unicode TR39 confusable skeleton,
 * case-folded (DOR-3156).
 *
 * A handle a person picks is refused when it reads as somebody else's —
 * `d0rian` for `dorian`, `rnia` for `mia` — even though the two strings differ.
 * The grammar (`HANDLE_PATTERN` in `@dorkos/shared/handle`) already rules out
 * every non-ASCII look-alike, so a Cyrillic `о` can never reach this code. What
 * is left is the look-alikes INSIDE the grammar's own alphabet.
 *
 * **The table is the standard's, not ours.** {@link CONFUSABLE_PROTOTYPES} is
 * every row of Unicode's `confusables.txt` (UTS #39) whose source character is
 * one a handle may contain, copied verbatim with its version. Regenerate it by
 * running `scripts/handle-confusables.ts` against a newer file; never add a row
 * by hand, because a hand-written row is a judgment the standard did not make.
 *
 * The skeleton follows TR39 §4 (map each character to its prototype), then
 * folds case, because the standard's prototype for `0` is a capital `O` while a
 * handle is always lowercase. Then {@link DORKOS_EXTRA_FOLDS} adds the few
 * look-alikes TR39 leaves apart, kept in their own named table so the
 * standard's rows stay generated.
 *
 * @module server/services/rooms/handles/handle-skeleton
 */

/** The `confusables.txt` version {@link CONFUSABLE_PROTOTYPES} was taken from. */
export const CONFUSABLES_VERSION = '18.0.0';

/**
 * Every `confusables.txt` row whose source is a character the handle grammar
 * allows (`a-z`, `0-9`, `.`, `_`, `-`), source to prototype. Generated by
 * `scripts/handle-confusables.ts`; do not edit by hand.
 */
export const CONFUSABLE_PROTOTYPES: Readonly<Record<string, string>> = {
  '0': 'O',
  '1': 'l',
  m: 'rn',
};

/**
 * Look-alikes TR39 does not join, folded on top of it (DOR-3156, Security and
 * PM 18:43). Hand-written on purpose, and only here.
 *
 * - `i` with `l` (and so with `1`, which TR39 already maps to `l`, and `I`,
 *   once case is folded): in most fonts `dor1an`, `dorian` and `dorlan` read
 *   the same, and TR39 maps `1` to `l` but not to `i`.
 * - `0` with `o`: TR39 maps `0` to capital `O`, which case folding already
 *   joins to `o`; stated here so the pair is visible beside the others.
 * - `.` and `_` with `-`: `@writer_ops`, `@writer.ops` and `@writer-ops` are
 *   one address to a reader, and to a model writing a mention from memory.
 */
export const DORKOS_EXTRA_FOLDS: Readonly<Record<string, string>> = {
  i: 'l',
  '0': 'o',
  '.': '-',
  _: '-',
};

/**
 * The look-alike key of a handle: two handles with the same skeleton read as
 * the same address.
 *
 * @param handle - A handle, normalized or not.
 */
export function handleSkeleton(handle: string): string {
  let mapped = '';
  for (const char of handle.toLowerCase()) mapped += CONFUSABLE_PROTOTYPES[char] ?? char;
  let folded = '';
  for (const char of mapped.toLowerCase()) folded += DORKOS_EXTRA_FOLDS[char] ?? char;
  return folded;
}

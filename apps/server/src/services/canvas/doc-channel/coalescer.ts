export type { CurrentQueueIntent } from './current/current-operation-types.js';
const currentQueueIntents = new WeakMap<DbTransaction, CurrentQueueIntent>();
function captureCurrentQueueIntent(
  store: DocChannelStore,
  tx: DbTransaction,
  access: DocIngestAccess,
  decision: DocRouteDecision,
  event: DocEventRow,
  batch: DocBatchRow | undefined,
  delivery: typeof canvasDocDeliveries.$inferSelect,
  priorInputs?: ReturnType<typeof captureCurrentBatchOriginalInputs>
): void {
  if (!isCurrentDocQueueScope(store, tx, event, access, decision)) return;
  let own = currentQueueIntents.get(tx);
  if (!own) {
    own = { store, eventId: event.eventId, routes: new Map(), superseded: [] };
    currentQueueIntents.set(tx, own);
  }
  if (own.store !== store || own.eventId !== event.eventId || own.routes.has(decision.route.id))
    throw new Error('Current route identity is already captured.');
  own.routes.set(
    decision.route.id,
    copyCurrentDocData({
      ...(batch
        ? {
            batch,
            inputs: buildCurrentRoomInputIntention(batch, priorInputs ?? [], event, delivery),
          }
        : {}),
      delivery,
    })
  );
}
/** Read only coalescer-generated original intentions; no caller registration or reset operation exists. */
export function readCurrentDocQueueAudit(
  store: DocChannelStore,
  tx: DbTransaction,
  event: DocEventRow
) {
  const own = currentQueueIntents.get(tx);
  if (!own) return []; // Exact expected route cardinality is separately validated by fixed ingestor.
  if (own.store !== store || own.eventId !== event.eventId)
    throw new Error('Current queue scope is foreign.');
  try {
    auditCurrentQueueRows(tx, event, own);
    return copyCurrentDocData([...own.routes.values()]);
  } catch (cause) {
    return failCurrentDocOperation(store, tx, cause);
  }
}
/** Read only pre-effect coalescer intentions, never a public store-derived replacement. */
export function readCurrentDocQueueDeliveries(
  store: DocChannelStore,
  tx: DbTransaction,
  event: DocEventRow
): readonly (typeof canvasDocDeliveries.$inferSelect)[] {
  readCurrentDocQueueAudit(store, tx, event);
  const own = currentQueueIntents.get(tx);
  return own ? [...own.routes.values()].map((route) => route.delivery) : [];
}
const originalQueueIdentities = new WeakMap<DbTransaction, Readonly<OriginalQueueIdentity>>();
/** Read only the identity generated by this coalescer in the genuine original scope. */
export function readOriginalCheckboxQueueIdentity(
  store: DocChannelStore,
  tx: DbTransaction,
  event: DocEventRow
): Readonly<{ batchId: string; generation: string }> {
  const own = originalQueueIdentities.get(tx);
  if (
    !isOriginalCheckboxQueueScope(store, tx, event) ||
    !own ||
    own.store !== store ||
    own.eventId !== event.eventId
  )
    throw new Error('Original checkbox queue identity is absent.');
  return Object.freeze({ batchId: own.batchId, generation: own.generation });
}
function retainOriginalQueueIdentity(
  store: DocChannelStore,
  tx: DbTransaction,
  event: DocEventRow,
  batchId: string,
  generation: string
): void {
  if (!isOriginalCheckboxQueueScope(store, tx, event)) return;
  if (originalQueueIdentities.has(tx))
    throw new Error('Original checkbox queue identity is already retained.');
  originalQueueIdentities.set(
    tx,
    Object.freeze({ store, eventId: event.eventId, batchId, generation })
  );
}


/** Unknown future controls still get a visible, unambiguous code-point label. */
export function hookControlName(character: string): string {
  const point = character.codePointAt(0)!.toString(16).toUpperCase();
  return NAMES[point] ?? `control U+${point.padStart(4, '0')}`;
}

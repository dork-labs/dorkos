#!/usr/bin/env node
// Rebuild the DorkOS-derived assets the frame serves:
//   assets/tokens.css  the portable palette (packages/ui/tokens.css) plus the
//                      client's semantic bridge (--background, --surface,
//                      --elevation-*, --status-*), for .light and .dark
//   assets/app.css     the client stylesheet compiled by Tailwind, so a screen
//                      that opts in (<meta name="vc-css" content="app">) can use
//                      bg-card, shadow-elevated, text-muted-foreground, text-sm...
//
// Both are generated and gitignored. `vc` builds them on first use; run
// `scripts/vc build` (or this file) to rebuild after the app's styles change.
//
// Usage: node build-assets.mjs [--dorkos <repo>] [--tokens-only]
// The repo is --dorkos, then $VC_DORKOS_REPO, then the git checkout this skill
// lives in (locate.cjs). Reads the DorkOS repo; writes only to assets/.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const { findDorkosRepo } = createRequire(import.meta.url)('./locate.cjs');
const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const opt = (n, d) => (args.indexOf(n) >= 0 ? args[args.indexOf(n) + 1] : d);
let dorkos;
try {
  dorkos = findDorkosRepo(opt('--dorkos'));
} catch (e) {
  console.error(e.message);
  process.exit(2);
}
const outDir = path.join(here, 'assets');
fs.mkdirSync(outDir, { recursive: true });
// Write beside the target, then rename, so a page or a second build never reads half a file.
const writeAtomic = (name, text) => {
  const tmp = path.join(outDir, '.' + name + '.' + process.pid + '.tmp');
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, path.join(outDir, name));
};

const clientCss = path.join(dorkos, 'apps/client/src/index.css');
const uiTokens = path.join(dorkos, 'packages/ui/tokens.css');

// ---------- tokens.css ----------
// Pull every top-level block whose selector is exactly `:root, .light` or `.dark`
// out of a stylesheet, by brace matching (no CSS parser needed for these files).
function blocks(css, wanted) {
  const out = [];
  // Neutralise strings that contain a comment opener (`@source '../dist/*.js'`),
  // then drop comments, so brace matching sees only rules.
  css = css.replace(/(['"])[^'"\n]*\/\*[^'"\n]*\1/g, '""').replace(/\/\*[\s\S]*?\*\//g, '');
  const re = /(^|\n)([^{}\n][^{}]*?)\{/g;
  let m;
  while ((m = re.exec(css))) {
    // Strip comments, then keep only what follows the last statement (`@import …;`).
    const sel = m[2]
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .split(';')
      .pop()
      .replace(/\s+/g, ' ')
      .trim();
    let depth = 1,
      i = re.lastIndex;
    while (depth && i < css.length) {
      if (css[i] === '{') depth++;
      else if (css[i] === '}') depth--;
      i++;
    }
    if (wanted.includes(sel)) out.push({ sel, body: css.slice(re.lastIndex, i - 1) });
    re.lastIndex = i;
  }
  return out;
}
const decls = (body) =>
  body
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split(';')
    .map((s) => s.trim())
    .filter((s) => s.startsWith('--'));
const ui = fs.readFileSync(uiTokens, 'utf8');
const client = fs.readFileSync(clientCss, 'utf8');
const pick = (css, sel) => blocks(css, [sel]).flatMap((b) => decls(b.body));
const light = [...pick(ui, ':root, .light'), ...pick(client, ':root, .light')];
const dark = [...pick(ui, '.dark'), ...pick(client, '.dark')];
const fonts = pick(client, ':root').filter((d) => d.startsWith('--font-'));
const fmt = (sel, list) =>
  sel +
  ' {\n' +
  [...new Map(list.map((d) => [d.split(':')[0], d])).values()]
    .map((d) => '  ' + d + ';')
    .join('\n') +
  '\n}\n';
const stamp = `/* Generated by build-assets.mjs from ${path.relative(dorkos, uiTokens)} and ${path.relative(dorkos, clientCss)} on ${new Date().toISOString().slice(0, 10)}. Do not edit; rebuild. */\n`;
writeAtomic(
  'tokens.css',
  stamp + fmt(':root', fonts) + fmt(':root, .light', light) + fmt('.dark', dark)
);
console.log(JSON.stringify({ wrote: 'assets/tokens.css', light: light.length, dark: dark.length }));

if (flag('--tokens-only')) process.exit(0);

// ---------- app.css ----------
// The client depends on @tailwindcss/vite; its own deps are the compiler and scanner.
const clientReq = createRequire(path.join(dorkos, 'apps/client/package.json'));
const req = createRequire(clientReq.resolve('@tailwindcss/vite'));
const { compile } = req('@tailwindcss/node');
const { Scanner } = req('@tailwindcss/oxide');
const base = path.dirname(clientCss);
const compiler = await compile(client, { base, onDependency: () => {} });
const sources = [
  ...compiler.sources.map((s) => ({ ...s, negated: !!s.negated })),
  { base, pattern: '**/*', negated: false },
  { base: path.join(dorkos, 'packages/ui/src'), pattern: '**/*', negated: false },
  // The skill's own docs and examples, so every class they show is in the snapshot.
  { base: path.resolve(here, '..'), pattern: '**/*.{md,html}', negated: false },
];
const candidates = new Scanner({ sources }).scan();
let css = compiler.build(candidates);
const header = `/* DorkOS client CSS snapshot for the visual companion. Built by build-assets.mjs from ${path.relative(dorkos, clientCss)} on ${new Date().toISOString().slice(0, 10)} (${candidates.length} candidates). Rebuild after the app's styles change. */\n`;
writeAtomic('app.css', header + css);
console.log(
  JSON.stringify({ wrote: 'assets/app.css', bytes: css.length, candidates: candidates.length })
);

/**
 * Regenerate the `building-dorkos-apps` operating skill from the vendored App
 * Builder Pack (DOR-4061).
 *
 * The pack lives in `dork-labs/marketplace` as the skill-pack `app-builder-pack`.
 * DorkOS ships one pinned version of it, copied byte for byte into
 * `packages/operating-skills/src/skills/app-builder-pack/` with its own
 * `MANIFEST.sha256`. The seeder cannot read that folder at run time (the CLI is
 * one bundle), so this script writes the skill's files into a TypeScript module
 * as string literals. `app-builder-pack.test.ts` fails when the module, the
 * folder and the pinned manifest hash disagree.
 *
 * To move to a new pack version: replace the folder with the new reviewed tree,
 * update `APP_BUILDER_PACK_PIN` in `building-dorkos-apps.ts` and the hash in the
 * test, run this script, and bump `OPERATING_SKILLS_VERSION`. A new version is a
 * content change: Security reads its diff first.
 *
 * Run with: `pnpm exec tsx packages/operating-skills/scripts/sync-app-builder-pack.ts`
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const SKILLS = path.resolve(import.meta.dirname, '..', 'src/skills');
const SOURCE = path.join(SKILLS, 'app-builder-pack', 'skills', 'building-dorkos-apps');
const TARGET = path.join(SKILLS, 'building-dorkos-apps.files.ts');

const files = readdirSync(SOURCE).sort();
const entries = files
  .map(
    (file) =>
      `  ${JSON.stringify(file)}: ${JSON.stringify(readFileSync(path.join(SOURCE, file), 'utf8'))},`
  )
  .join('\n');

writeFileSync(
  TARGET,
  `/**
 * GENERATED by \`packages/operating-skills/scripts/sync-app-builder-pack.ts\` from
 * \`./app-builder-pack/skills/building-dorkos-apps/\`. Do not edit by hand: the
 * strings must stay byte-equal to the vendored pack, which
 * \`__tests__/app-builder-pack.test.ts\` checks.
 *
 * @module skills/building-dorkos-apps.files
 */

/** The vendored skill's files, by name, exactly as the pinned pack ships them. */
export const BUILDING_DORKOS_APPS_FILES = {
${entries}
} as const;
`
);
execFileSync('pnpm', ['exec', 'prettier', '--write', TARGET], { stdio: 'inherit' });
console.log(`Wrote ${files.length} files into ${path.relative(process.cwd(), TARGET)}`);

/**
 * Checks the launcher's Fly GraphQL documents against Fly's real schema, without a GraphQL
 * library.
 *
 * Three paid live runs stopped on answers the fixtures had invented; one of them was a query for a
 * root field (`node`) that Fly's API does not have. A fixture can only prove the parser agrees with
 * the fixture. This proves every field, argument, input field and inline-fragment type the
 * documents name exists in the schema Fly serves, using a trimmed introspection snapshot that the
 * contract replay (`community-deploy-contract-replay.ts`) regenerates from the live API.
 *
 * The parser understands exactly the GraphQL the launcher writes: one named operation with typed
 * variables, fields with arguments whose values are variables or object literals, and `... on Type`
 * inline fragments. Anything else is reported as unsupported rather than silently accepted.
 */
import { resolve } from 'node:path';
